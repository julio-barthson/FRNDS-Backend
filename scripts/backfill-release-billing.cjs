/**
 * Seeds `ReleaseContributor` for releases created before billing existed.
 *
 * Every release made until now was implicitly billed to the account that
 * uploaded it — that was the only thing it could be, because `Release.artistId`
 * was the sole notion of who a release was by. This writes that same fact down
 * explicitly, so those releases carry a primary artist and can still pass the
 * submission check that now requires one.
 *
 * Run it after `prisma db push`, from the backend directory:
 *   node scripts/backfill-release-billing.cjs
 *
 * Raw SQL over the Neon driver rather than the Prisma client, for two reasons.
 * Prisma 7's `prisma-client` generator emits TypeScript — `src/generated/prisma`
 * holds `client.ts`, not `client.js` — so plain `node` cannot require it, and
 * the app only works because Nest compiles it into `dist/` first. Making a
 * one-off script depend on a build, or on ts-node, to run a single INSERT is a
 * poor trade. The driver's HTTP transport also sidesteps the blocked Postgres
 * TCP port, so this runs from anywhere the app itself can reach the database.
 *
 * Safe to run repeatedly: `NOT EXISTS` skips releases that already have
 * billing, so a second run is a no-op.
 */
const { neon } = require('@neondatabase/serverless');

require('dotenv').config();

async function main() {
  const connectionString = process.env.DATABASE_URL;
  if (!connectionString) throw new Error('DATABASE_URL is not set');

  const sql = neon(connectionString);

  // `id` is filled in here because Prisma's `@default(uuid())` is generated by
  // the client, not by the column — there is no database-side default to lean
  // on. `gen_random_uuid()` is built into Postgres 13 and up.
  const inserted = await sql`
    INSERT INTO "ReleaseContributor" ("id", "releaseId", "name", "role", "position", "createdAt")
    SELECT gen_random_uuid(),
           r."id",
           a."stageName",
           'PRIMARY_ARTIST'::"ContributorRole",
           0,
           NOW()
    FROM "Release" r
    JOIN "Artist" a ON a."id" = r."artistId"
    WHERE NOT EXISTS (
      SELECT 1 FROM "ReleaseContributor" rc WHERE rc."releaseId" = r."id"
    )
    RETURNING "releaseId", "name"
  `;

  if (inserted.length === 0) {
    console.log('Nothing to backfill — every release already has billing.');
    return;
  }

  console.log(`Wrote ${inserted.length} primary artist row(s):`);
  for (const row of inserted) {
    console.log(`  ${row.releaseId} → ${row.name}`);
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
